/** Every translation key. */
export type ProbeKey = keyof typeof zh

/** Replace `{name}` placeholders. */
export function t(dictionary: Record<string, string>, key: string, values?: Record<string, string | number>): string {
  const template = dictionary[key] ?? zh[key as ProbeKey] ?? key
  if (values === undefined) return template
  return template.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name]
    return value === undefined ? match : String(value)
  })
}
